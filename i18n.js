let shzLang = (typeof navigator !== "undefined" && /^ja/i.test(navigator.language || "")) ? "ja" : "en";
const shzResolveLang = (setting) => (setting === "ja" || setting === "en" ? setting : (typeof navigator !== "undefined" && /^ja/i.test(navigator.language || "") ? "ja" : "en"));

function shzT(key, vars) {
  const s = (SHZ_I18N[shzLang] && SHZ_I18N[shzLang][key]) ?? SHZ_I18N.ja[key] ?? key;
  return vars ? s.replace(/\{(\w+)\}/g, (_, k) => (k in vars ? String(vars[k]) : `{${k}}`)) : s;
}

// 保存された言語の設定を読んで、shzLang に反映する。変わったときは onChange を呼ぶ
function shzLoadLang(onChange) {
  chrome.storage.local.get({ lang: "auto" }, (v) => { shzLang = shzResolveLang(v.lang); if (onChange) onChange(); });
  chrome.storage.onChanged.addListener((c, area) => {
    if (area !== "local" || !c.lang) return;
    shzLang = shzResolveLang(c.lang.newValue);
    if (onChange) onChange();
  });
}
